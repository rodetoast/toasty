import subprocess
from datetime import date
from pathlib import Path


ROOT_DIR = Path(__file__).resolve().parent
BUILD_INFO_PATH = ROOT_DIR / "_build_info.py"


def run_git(args):
    result = subprocess.run(
        ["git", *args],
        cwd=ROOT_DIR,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def main():
    build_hash = run_git(["rev-parse", "--short", "HEAD"])
    full_commit = run_git(["rev-parse", "HEAD"])
    build_date = date.today().isoformat()

    BUILD_INFO_PATH.write_text(
        "\n".join(
            [
                "# Generated by create_build_info.py. Do not edit or commit.",
                f'BUILD_HASH = "{build_hash}"',
                f'FULL_COMMIT = "{full_commit}"',
                f'BUILD_DATE = "{build_date}"',
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(f"created {BUILD_INFO_PATH.name}: {build_hash} ({build_date})")


if __name__ == "__main__":
    main()
